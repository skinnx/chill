#!/usr/bin/env python3
"""Generate scripts/core/nfc_table.gd: canonical composition pairs for the shipped glyph set.

Godot 4.7 exposes no Unicode normalisation to GDScript, but GDD §7.3 requires player-typed names
to be NFC before saving (some Vietnamese keyboards emit decomposed sequences). The fonts only
cover Latin + Vietnamese (tools/fonts/build_fonts.py), so composition is only needed for that
set: every precomposed letter in the covered ranges whose canonical decomposition is a
(base, combining mark) pair. scripts/core/name_rules.gd applies the pairs after a canonical
reordering of the marks by combining class.

Usage: python3 -I tools/i18n/gen_nfc_table.py
"""
from __future__ import annotations

import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "scripts" / "core" / "nfc_table.gd"
RANGES = [(0x00C0, 0x024F), (0x1E00, 0x1EFF)]


def main() -> int:
	pairs: dict[tuple[int, int], int] = {}
	marks: dict[int, int] = {}
	for lo, hi in RANGES:
		for cp in range(lo, hi + 1):
			ch = chr(cp)
			dec = unicodedata.decomposition(ch)
			if not dec or dec.startswith("<"):
				continue  # no canonical decomposition, or a compatibility one
			parts = [int(x, 16) for x in dec.split()]
			if len(parts) != 2:
				continue
			if unicodedata.normalize("NFC", chr(parts[0]) + chr(parts[1])) != ch:
				continue  # composition exclusion
			pairs[(parts[0], parts[1])] = cp
			marks[parts[1]] = unicodedata.combining(chr(parts[1]))
	lines = [
		"class_name NfcTable",
		"extends RefCounted",
		"## GENERATED by tools/i18n/gen_nfc_table.py (Unicode %s). Do not edit." % unicodedata.unidata_version,
		"## Canonical composition pairs for Latin + Vietnamese: (base << 21 | mark) -> composed.",
		"",
		"## Combining mark -> canonical combining class (for reordering before composition).",
		"const COMBINING_CLASS := {",
	]
	for m in sorted(marks):
		lines.append("\t0x%04X: %d," % (m, marks[m]))
	lines.append("}")
	lines.append("")
	lines.append("const PAIRS := {")
	for (b, m), c in sorted(pairs.items()):
		lines.append("\t0x%X: 0x%04X,  # %s" % ((b << 21) | m, c, chr(c)))
	lines.append("}")
	OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
	print(f"wrote {OUT.relative_to(ROOT)}: {len(pairs)} pairs, {len(marks)} marks")
	return 0


if __name__ == "__main__":
	sys.exit(main())
